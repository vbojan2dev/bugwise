export type Currency = 'EUR' | 'RSD';
export const currencyOf = (lang: Lang): Currency => (lang === 'sr' ? 'RSD' : 'EUR');

/** Price formatting. Serbian uses en-US separators instead of sr-Latn (1,299.00 RSD instead of 1.299,00 RSD). */
export function money(n: number, lang: Lang, cur: Currency = currencyOf(lang)) {
  const opts = { minimumFractionDigits: 2, maximumFractionDigits: 2 };
  if (lang === 'de') return `${n.toLocaleString('de-DE', opts)} ${cur === 'EUR' ? '€' : 'RSD'}`;
  if (lang === 'sr') return `${n.toLocaleString('en-US', opts)} ${cur === 'EUR' ? '€' : 'RSD'}`; // BUG B21
  return cur === 'EUR' ? `€${n.toLocaleString('en-US', opts)}` : `${n.toLocaleString('en-US', opts)} RSD`;
}

/** The cart "Total" row: prints the raw number (BUG B10). */
export function rawMoney(n: number, lang: Lang, cur: Currency = currencyOf(lang)) {
  const s = String(n);
  if (lang === 'de') return `${s.replace('.', ',')} ${cur === 'EUR' ? '€' : 'RSD'}`;
  if (lang === 'sr') return `${s} ${cur === 'EUR' ? '€' : 'RSD'}`;
  return cur === 'EUR' ? `€${s}` : `${s} RSD`;
}

export const hhmm = (minutes: number) => {
  const m = ((Math.round(minutes) % 1440) + 1440) % 1440;
  return `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;
};
export const clockOf = (ms: number) => {
  const dt = new Date(ms);
  return dt.getHours() * 60 + dt.getMinutes();
};
